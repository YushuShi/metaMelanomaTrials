'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const CI=require('../dist/confidence_intervals.js'),Analysis=require('../dist/treatment_map_analysis.js'),Effects=require('../dist/treatment_map_effects.js'),Quantitative=require('../dist/quantitative_extraction.js');
const close=(a,b,tolerance=1e-12)=>assert.ok(Math.abs(a-b)<=tolerance,`${a} differs from ${b}`);
const record=(changes={})=>({id:'one',measure:'HR',outcome:'OS',estimate:.88,ci_lower:.69,ci_upper:1.11,ci_level:95.03,intervention:{node_id:'ab'},comparator:{node_id:'a'},...changes});

test('reported 95.03% interval is converted with original-level log-Wald precision and explicitly labelled',()=>{
  const source=record(),before=JSON.stringify(source),out=CI.forDisplay(source);
  // Independent scipy.stats.norm.ppf calculation, not generated by the JS helper.
  close(out.precision_se,.12112477429954839);close(out.ci_lower,.6940345285406562);close(out.ci_upper,1.115794630028463);
  assert.equal(out.estimate,.88);assert.equal(out.ci_level,95);assert.equal(out.ci_converted,true);
  assert.equal(out.ci_conversion_method,'approximate_wald_log');assert.match(out.conversion_note,/reported 95.03%/);
  assert.deepEqual(out.original_ci,{estimate:.88,ci_lower:.69,ci_upper:1.11,ci_level:95.03});assert.equal(JSON.stringify(source),before);
  const repeat=CI.forDisplay({...source,...out});assert.deepEqual(repeat,out);
  assert.deepEqual(CI.forDisplay({...source,...out},{original:true}).original_ci,out.original_ci);
});

test('99.5% and 90% conversions agree with independent normal-quantile fixtures across supported ratio measures',()=>{
  for(const measure of ['HR','RR','OR','TR','hazard ratio','time_ratio']){
    const a=CI.forDisplay(record({measure,estimate:.7,ci_lower:.39,ci_upper:1.26,ci_level:99.5}));
    close(a.precision_se,.20888958908281197);close(a.ci_lower,.46482652138847153);close(a.ci_upper,1.0541567175133066);
    const b=CI.forDisplay(record({measure,estimate:.8,ci_lower:.5,ci_upper:1.2,ci_level:90}));
    close(b.precision_se,.2661235999997376);close(b.ci_lower,.4748595405651955);close(b.ci_upper,1.3477669612328906);
  }
  assert.equal(CI.confidenceLevel(.995),99.5);assert.equal(CI.confidenceLevel(1),null);assert.equal(CI.confidenceLevel(100),null);
});

test('native 95% intervals are never recentered, rerounded or flagged as converted',()=>{
  const source=record({ci_level:95}),out=CI.forDisplay(source);
  assert.equal(out.ci_lower,.69);assert.equal(out.ci_upper,1.11);assert.equal(out.estimate,.88);assert.equal(out.ci_converted,false);
  assert.equal(CI.forDisplay({...source,ci_level:.95}).ci_lower,.69);
  const unknown=CI.forDisplay({...source,ci_level:undefined});assert.equal(unknown.ci_lower,.69);assert.equal(unknown.ci_level_assumed,true);assert.equal(unknown.ci_converted,false);
});

test('arbitrary median, proportion and explicit exact/profile/bootstrap intervals are not falsely relabelled as 95%',()=>{
  for(const changes of [{measure:'median'},{measure:'proportion'},{ci_method:'exact conditional'},{ci_method:'profile likelihood'},{ci:{method:'bootstrap percentile'}},{confidence_interval_method:'Bayesian credible'}]){
    const result=CI.forDisplay(record({...changes,ci_level:90}));assert.equal(result.ci_converted,false);assert.equal(result.ci_level,90);assert.equal(result.ci_lower,null);assert.equal(result.original_ci.ci_lower,.69);assert.equal(result.ci_95_unavailable,true);assert.equal(result.precision_se,null);assert.equal(result.ci_conversion_status,'unsupported_method');assert.match(result.conversion_note,/cannot be recovered/);
  }
  for(const changes of [{ci_lower:null},{ci_upper:0},{ci_upper:.5},{ci_level:100}])assert.equal(CI.forDisplay(record(changes)).ci_converted,false);
  for(const level of [5,9]){const held=CI.forDisplay(record({ci_level:level}));assert.equal(held.ci_converted,false);assert.equal(held.ci_conversion_status,'source_level_review');assert.equal(held.precision_se,null);assert.equal(held.ci_lower,null);assert.equal(held.original_ci.ci_lower,.69);}
  const normalized=Analysis.normalizeRow(record({ci_level:90,ci_method:'profile likelihood'}),'ab','a');
  assert.equal(normalized.se,null);assert.equal(Analysis.poolRows([normalized]),null);assert.equal(normalized.ci_95_unavailable,true);
});

test('source wrappers are accepted without mutating confidence-level facts or original drawer values',()=>{
  const fact=value=>({value,status:'reported'}),source={measure:'HR',estimate:fact(.88),ci_lower:fact(.69),ci_upper:fact(1.11),confidence_level:fact(95.03)};
  const out=CI.forDisplay(source);assert.equal(out.ci_converted,true);assert.equal(out.original_ci.ci_level,95.03);assert.equal(source.confidence_level.value,95.03);
  assert.match(Quantitative.interval(record()),/approximate 95% CI, converted/);
  assert.equal(Quantitative.interval(record(),.88,{original:true}),'0.880 (0.690–1.110; 95.03% CI)');
  const median={measure:'median',estimate:12,ci_lower:9,ci_upper:15,ci_level:90};
  assert.equal(Quantitative.interval(median),'12.000 (95% CI unavailable)');assert.equal(Quantitative.interval(median,12,{original:true}),'12.000 (9.000–15.000; 90% CI)');
  const masked=CI.forDisplay({...source,estimate:{...source.estimate,semantic_non_scalar_source_literal:true}});assert.equal(masked.ci_converted,false);
  const lowWald=CI.forDisplay(record({ci_level:9,ci_method:'normal Wald'}));assert.equal(lowWald.ci_converted,true);assert.equal(lowWald.original_ci.ci_level,9);
});

test('every released map source keeps its original precision and all 51 non95 HR intervals become marked 95% display intervals',()=>{
  const fs=require('node:fs'),path=require('node:path'),graph=JSON.parse(fs.readFileSync(path.join(__dirname,'../dist/data/treatment_map.json'),'utf8'));
  const before=JSON.stringify(graph),converted=[];
  for(const source of graph.comparisons){
    const row=Analysis.normalizeRow(source,Effects.armId(source.comparator),Effects.armId(source.intervention));
    if(!row)continue;
    const level=Analysis.confidenceLevel(source.ci_level),valid=source.ci_lower>0&&source.ci_upper>source.ci_lower&&source.estimate>=source.ci_lower&&source.estimate<=source.ci_upper;
    if(valid){const expected=(Math.log(source.ci_upper)-Math.log(source.ci_lower))/(2*Analysis.normalQuantile(.5+level/200));assert.equal(row.se,expected);}
    if(level!==95&&valid){assert.equal(row.ci_level,95);assert.equal(row.ci_converted,true);assert.equal(row.original_ci.ci_level,source.ci_level);converted.push(source);}
    else if(valid){assert.equal(row.ci_lower,source.ci_lower);assert.equal(row.ci_upper,source.ci_upper);assert.equal(row.ci_converted,false);}
  }
  assert.equal(converted.length,51);assert(converted.some(row=>row.pmid==='41124198'&&row.ci_level===95.03));assert.equal(JSON.stringify(graph),before);
});

test('directed effects use standardized null coverage and reciprocal conversion is idempotent',()=>{
  // A 99% interval covers the null, but its standardized 95% interval excludes it.
  const source=record({estimate:.7,ci_lower:.45,ci_upper:1.08,ci_level:99});
  const forward=Effects.directedEffect(source,'ab','a'),reverse=Effects.directedEffect(source,'a','ab');
  assert.equal(forward.ciExcludesNull,true);assert.equal(reverse.ciExcludesNull,true);assert.equal(forward.ci_level,95);
  close(reverse.ci_lower,1/forward.ci_upper);close(reverse.ci_upper,1/forward.ci_lower);
  assert.deepEqual(Effects.directedEffect({...source,...CI.forDisplay(source)},'a','ab').original_ci,reverse.original_ci);
  close(Effects.directedEffect({...source,...CI.forDisplay(source)},'a','ab').ci_lower,reverse.ci_lower);
});

test('conversion never changes inverse-variance weights, pooled estimates or diagnostics precision',()=>{
  const sources=[record(),record({id:'two',estimate:.72,ci_lower:.4,ci_upper:1.2,ci_level:99.5}),record({id:'three',estimate:1.1,ci_lower:.8,ci_upper:1.6,ci_level:90})];
  const normalized=sources.map(source=>Analysis.normalizeRow(source,'a','ab'));
  const raw=sources.map((source,i)=>{const se=(Math.log(source.ci_upper)-Math.log(source.ci_lower))/(2*Analysis.normalQuantile(.5+source.ci_level/200));return {...normalized[i],ci_converted:false,original_ci:null,ci_lower:source.ci_lower,ci_upper:source.ci_upper,ci_level:source.ci_level,se,variance:se*se};});
  normalized.forEach((row,i)=>assert.equal(row.variance,raw[i].variance));
  const a=Analysis.poolRows(normalized),b=Analysis.poolRows(raw);
  for(const field of ['estimate','ci_lower','ci_upper','tau2','Q','I2','p_value'])assert.equal(a[field],b[field]);
  assert.deepEqual(a.weight_percent,b.weight_percent);assert.equal(a.ci_converted,false);
  const two=normalized.slice(0,2),loo=Analysis.diagnostics(two,Analysis.poolRows(two)).leave_one_out;
  loo.forEach((row,i)=>{assert.equal(row.ci_level,95);assert.equal(row.ci_converted,true);assert.equal(row.original_ci.ci_level,sources[1-i].ci_level);assert.match(row.conversion_note,/Approximate/);});
});
